import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const base = new URL('./', import.meta.url);
const shared = await readFile(new URL('../kct.js', base), 'utf8');
const boundary = '// ---------------------------------------------------------------------------\n// styles\n';
assert.equal(shared.split(boundary).length, 2, 'Shared core boundary changed; review browser build.');
const core = shared.slice(0, shared.indexOf(boundary));
assert(core.includes('async function translateText(') && core.includes('async function translateBing('));
await mkdir(new URL('dist/', base), { recursive: true });
for (const name of ['manifest.json', 'background.mjs', 'content.js']) {
  await copyFile(new URL(name, base), new URL(`dist/${name}`, base));
}
// Keep the shared translation engine; neither desktop boot nor page storage runs.
await writeFile(new URL('dist/core.js', base), `// Generated by browser/build.mjs; kct.js SHA256: ${createHash('sha256').update(shared).digest('hex')}\n(() => {
  const localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
  const fetch = async (url, options) => {
    const parsed = new URL(url);
    if (parsed.origin !== 'https://edge.microsoft.com' ||
        parsed.pathname !== '/translate/translatetext' || options.method !== 'POST') {
      throw new Error('Browser adapter supports Bing only');
    }
    if (options.signal?.aborted) throw new Error('Translation cancelled');
    let reply;
    try {
      reply = await chrome.runtime.sendMessage({
        kind: 'kct.bing', texts: JSON.parse(options.body), lang: parsed.searchParams.get('to')
      });
    } catch (cause) {
      const error = cause instanceof Error ? cause : new Error(String(cause));
      error.network = true;
      throw error;
    }
    if (!reply?.ok) {
      const error = new Error(reply?.error || 'Translation failed');
      for (const field of ['status', 'retryAfterMs', 'network']) {
        if (reply?.[field] !== undefined) error[field] = reply[field];
      }
      if (reply?.network === true) error.network = true;
      throw error;
    }
    return { ok: true, json: async () => reply.payload };
  };
${core}
  globalThis.KCTBrowserCore = { translateText, languages: TARGET_LANGUAGES };
})();
`);
console.log(`Unpacked MV3 extension: ${fileURLToPath(new URL('dist/', base))}`);
